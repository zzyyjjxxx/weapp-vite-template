import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const MIN_PARENT_ID = 181
const MAX_PARENT_ID = 439
const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url))
const OUTPUT_PATH = resolve(SCRIPT_DIRECTORY, '../src/features/land-demand/dictionaries/industries.generated.ts')

function unquoteSqlString(value) {
  return value.slice(1, -1).replace(/\\(.)/g, '$1')
}

function parseIndustryRows(sql) {
  const rows = []
  const insertPattern = /INSERT\s+INTO\s+`?m_industryinfo`?\s+VALUES\s*\((.*?)\);/g

  for (const match of sql.matchAll(insertPattern)) {
    const values = match[1].match(/'(?:\\.|[^'\\])*'|NULL|-?\d+/g)

    if (!values || values.length !== 4) {
      throw new Error(`Unable to parse m_industryinfo row: ${match[0]}`)
    }

    const [, industryCode, industryName, pid] = values
    if (pid === 'NULL') {
      continue
    }

    rows.push({
      industryCode: unquoteSqlString(industryCode),
      industryName: unquoteSqlString(industryName),
      pid: unquoteSqlString(pid),
    })
  }

  if (rows.length === 0) {
    throw new Error('No m_industryinfo INSERT rows were found')
  }

  return rows
}

function compareNumerically(left, right) {
  return Number(left) - Number(right)
}

function createGroups(rows) {
  const rowsByCode = new Map(rows.map(row => [row.industryCode, row]))
  const leaves = rows
    .filter((row) => {
      const parentId = Number(row.pid)
      return Number.isInteger(parentId) && parentId >= MIN_PARENT_ID && parentId <= MAX_PARENT_ID
    })
    .map(row => ({ ...row, label: `${row.industryName}（${row.industryCode}）` }))
    .sort((left, right) => compareNumerically(left.industryCode, right.industryCode))
  const leavesByParent = new Map()

  for (const leaf of leaves) {
    const children = leavesByParent.get(leaf.pid) ?? []
    children.push(leaf)
    leavesByParent.set(leaf.pid, children)
  }

  const groups = [...leavesByParent.entries()]
    .map(([parentCode, children]) => {
      const parent = rowsByCode.get(parentCode)
      if (!parent) {
        throw new Error(`Missing parent industry for pid ${parentCode}`)
      }

      return {
        value: parent.industryCode,
        label: parent.industryName,
        children,
      }
    })
    .sort((left, right) => compareNumerically(left.value, right.value))

  return groups
}

function quoteTypeScript(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
}

function renderLeaf(leaf, indent) {
  return [
    `${indent}{`,
    `${indent}  industryCode: ${quoteTypeScript(leaf.industryCode)},`,
    `${indent}  industryName: ${quoteTypeScript(leaf.industryName)},`,
    `${indent}  pid: ${quoteTypeScript(leaf.pid)},`,
    `${indent}  label: ${quoteTypeScript(leaf.label)},`,
    `${indent}},`,
  ].join('\n')
}

function renderGroups(groups) {
  return groups.map(group => [
    '  {',
    `    value: ${quoteTypeScript(group.value)},`,
    `    label: ${quoteTypeScript(group.label)},`,
    '    children: [',
    group.children.map(leaf => renderLeaf(leaf, '      ')).join('\n'),
    '    ],',
    '  },',
  ].join('\n')).join('\n')
}

function renderModule(groups) {
  return `// Generated by scripts/generate-industry-dictionary.mjs. Do not edit manually.\n\nexport interface IndustryLeaf {\n  industryCode: string\n  industryName: string\n  pid: string\n  label: string\n}\n\nexport interface IndustryGroup {\n  value: string\n  label: string\n  children: IndustryLeaf[]\n}\n\nexport const INDUSTRY_GROUPS: readonly IndustryGroup[] = [\n${renderGroups(groups)}\n]\n\nexport function getIndustryLabel(code: string): string | undefined {\n  for (const group of INDUSTRY_GROUPS) {\n    const industry = group.children.find(item => item.industryCode === code)\n    if (industry) return industry.label\n  }\n\n  return undefined\n}\n`
}

const sqlPath = process.argv[2]
if (!sqlPath) {
  throw new Error('Usage: node scripts/generate-industry-dictionary.mjs <m_industryinfo.sql path>')
}

const sql = await readFile(resolve(sqlPath), 'utf8')
const groups = createGroups(parseIndustryRows(sql))

await mkdir(dirname(OUTPUT_PATH), { recursive: true })
await writeFile(OUTPUT_PATH, renderModule(groups), 'utf8')

console.log(`Generated ${groups.length} industry groups with ${groups.reduce((total, group) => total + group.children.length, 0)} leaves`)
